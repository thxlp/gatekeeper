// template อีเมลของระบบ (plain-text ภาษาไทย) — รวมไว้ที่เดียวให้แก้ข้อความง่าย
//
// ตั้งใจเป็น plain-text ไม่ใช่ HTML: อีเมลของระบบเป็นการ "แจ้งให้ทราบ" และ "ยืนยันตัวตน"
// ไม่ใช่สื่อการตลาด — plain-text ถึงกล่องจดหมายแน่นอนกว่า ไม่โดนตัดรูป/บล็อก CSS และถูกจัด
// เป็นสแปมน้อยกว่า (สำคัญมากกับอีเมล OTP ที่ผู้ใช้ต้องได้รับภายในไม่กี่วินาที)

export interface MailContent {
  subject: string;
  text: string;
}

const SERVICE_NAME = 'Gatekeeper';

/** ลิงก์ของระบบที่ใช้ในเมล — อิง FRONTEND_URL เดียวกับที่ระบบใช้จริง ไม่ฮาร์ดโค้ดโดเมน */
function siteUrl(): string {
  return (process.env.FRONTEND_URL || 'https://studiodup.com').replace(/\/+$/, '');
}

/**
 * ลายเซ็นท้ายอีเมลทุกฉบับ — ให้ผู้รับรู้ว่าอีเมลมาจากใคร ตอบกลับได้ไหม และไปจัดการต่อที่ไหน
 * (อีเมลที่ไม่บอกที่มาและตอบกลับไม่ได้ ถูกมองว่าเป็นสแปมทั้งจากคนและจากตัวกรอง)
 */
function footer(): string {
  return [
    '—',
    `${SERVICE_NAME} · ระบบตรวจสอบและนำส่งแอปพลิเคชันอัตโนมัติ`,
    siteUrl(),
    '',
    'อีเมลฉบับนี้ส่งโดยระบบอัตโนมัติ กรุณาอย่าตอบกลับ',
  ].join('\n');
}

/** ประกอบเนื้อเมล: ย่อหน้าเนื้อหา + ลายเซ็นท้าย */
function compose(lines: string[]): string {
  return [...lines, '', footer()].join('\n');
}

export function deployFailedEmail(appName: string, reason: string): MailContent {
  return {
    subject: `[${SERVICE_NAME}] แจ้งผลการนำส่ง: ไม่สำเร็จ — ${appName}`,
    text: compose([
      'เรียน ผู้ใช้บริการ',
      '',
      `ระบบขอแจ้งให้ทราบว่าการนำส่ง (deploy) แอปพลิเคชัน "${appName}" ไม่สำเร็จ`,
      '',
      `สาเหตุ: ${reason}`,
      '',
      'แอปพลิเคชันเวอร์ชันก่อนหน้า (หากมี) ยังให้บริการตามปกติ ไม่ได้รับผลกระทบ',
      `ท่านสามารถตรวจสอบรายละเอียดผลการตรวจสอบความปลอดภัยได้ที่หน้า Audit Log: ${siteUrl()}/audit`,
    ]),
  };
}

export function rollbackFailedEmail(appName: string, reason: string): MailContent {
  return {
    subject: `[${SERVICE_NAME}] แจ้งผลการย้อนเวอร์ชัน: ไม่สำเร็จ — ${appName}`,
    text: compose([
      'เรียน ผู้ใช้บริการ',
      '',
      `ระบบขอแจ้งให้ทราบว่าการย้อนกลับไปเวอร์ชันก่อนหน้า (rollback) ของแอปพลิเคชัน "${appName}" ไม่สำเร็จ`,
      '',
      `สาเหตุ: ${reason}`,
      '',
      'แอปพลิเคชันที่ให้บริการอยู่ขณะนี้ยังทำงานตามเดิม ไม่ได้รับผลกระทบ',
      'ท่านสามารถเลือกย้อนไปเวอร์ชันอื่น หรือนำส่งเวอร์ชันใหม่อีกครั้งได้จากหน้าแอปพลิเคชัน',
    ]),
  };
}

