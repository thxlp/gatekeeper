/**
 * สวิตช์เปิด/ปิดฟีเจอร์ 2FA ทั้งระบบ (ไม่ใช่ค่าต่อบัญชี — ค่าต่อบัญชีคือ accounts.two_factor_enabled)
 *
 * **ค่าเริ่มต้นคือ "ปิดปรับปรุง"** ต้องตั้ง FEATURE_2FA=1 ให้ชัดเจนเท่านั้นถึงจะเปิดใช้งาน
 * ตั้งใจให้ default ปิด เพราะ 2FA พึ่งการส่งอีเมล ซึ่งพังเงียบมาแล้วจนผู้ใช้ล็อกเอาต์
 * (ดู docs/INCIDENT-2026-08-08-2fa-mail.md) — เปิดโดยไม่ได้ตั้งใจแล้วเมลส่งไม่ออก
 * = ทุกคนที่เปิด 2FA ไว้เข้าระบบไม่ได้ทันที ค่าเสียหายสูงกว่าการต้องตั้ง env เพิ่มหนึ่งบรรทัดมาก
 *
 * ปิดอยู่ = login ข้ามขั้นตอน OTP ไปเลยแม้บัญชีนั้นจะมี two_factor_enabled=true ค้างอยู่
 * (ค่าใน DB ไม่ถูกแตะ — เปิดฟีเจอร์กลับมาเมื่อไหร่ บัญชีนั้นก็กลับมาโดนบังคับ 2FA เหมือนเดิม)
 * ส่วน endpoint เปิด/ปิด 2FA ตอบ 503 ทั้งหมด
 *
 * อ่าน env ตอนเรียกทุกครั้ง ไม่ cache — จะได้สลับค่าแล้ว restart อย่างเดียวพอ ไม่ต้อง build ใหม่
 */
export function isTwoFactorAvailable(): boolean {
  // รับทั้ง 1 และ true — คนตั้ง env มักพิมพ์ true แล้วงงว่าทำไมไม่ติด ส่วนค่าอื่น (รวมค่าว่าง
  // และค่าที่พิมพ์ผิด) ตกเป็น "ปิด" หมด ซึ่งเป็นฝั่งที่ปลอดภัยกว่า: ปิด = เข้าระบบได้ตามปกติ
  const v = (process.env.FEATURE_2FA || '').trim().toLowerCase();
  return v === '1' || v === 'true';
}

